"""Project installation runtime: discovery, receipt and launcher (IF-PROJLAYOUT-001).

The receipt at ``<project>/.tracks/install.json`` is the single source of
truth for a project's locked version (interfaces §1b/§1d).  Discovery walks
up from the current directory; install artifacts without a receipt mean the
project is corrupt and must fail closed instead of falling back to the
global version.
"""

from __future__ import annotations

import contextlib
import http.client
import json
import os
import re
import signal
import subprocess
import sys
import time
from pathlib import Path

RECEIPT_REL = ".tracks/install.json"
LAUNCHER_REL = ".tracks/bin/trac.py"
SITE_PACKAGES_TEMPLATE = ".tracks/env/{version}/site-packages"
SERVICE_DIR_REL = ".tracks/service"
PIDFILE_NAME = "serve.pid"
SERVICE_LOG_NAME = "serve.log"
# A stopped service must leave promptly; SIGKILL only backstops a wedged one.
STOP_TIMEOUT_S = 5.0

# `.tracks` scaffold gitignores mirror `trac init`'s .tracks-level semantics
# (interfaces §1b.4); the host root .gitignore is deliberately never touched.
RUNTIME_GITIGNORE = "tracks.db*\nblobs/\nlock\nlog/\nprompts/\n"
PROJECTS_GITIGNORE = "*.lock\n*.tmp\n"
TRACKS_GITIGNORE = "report/\n*.lock\n"
ENV_GITIGNORE = "*"

_VERSION_ASSIGNMENT = re.compile(
    r'^__version__\s*=\s*["\']([^"\']+)["\']', re.MULTILINE
)

LAUNCHER_SOURCE = '''"""tracks project launcher (generated by ``trac install``).

Loads the locked site-packages recorded in ``.tracks/install.json`` and
runs the locked CLI from the project root with ``TRAC_PROJECT_ACTIVE=1``.
"""

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main(argv=None):
    receipt = json.loads(
        (ROOT / ".tracks" / "install.json").read_text(encoding="utf-8")
    )
    site_packages = (ROOT / receipt["site_packages"]).resolve()
    sys.path.insert(0, str(site_packages))
    os.chdir(ROOT)
    os.environ["TRAC_PROJECT_ACTIVE"] = "1"
    from tracks.cli.main import main as cli_main

    return cli_main(list(sys.argv[1:] if argv is None else argv))


if __name__ == "__main__":
    raise SystemExit(main())
'''


class ProjectCorrupt(Exception):
    """Install artifacts exist but the receipt/site-packages are unusable."""


def find_project(cwd: Path) -> Path | None:
    """Return the nearest installed project root, or None outside a project.

    Raises :class:`ProjectCorrupt` when a ``.tracks`` directory carries
    install artifacts (launcher or env) without a receipt.
    """
    current = Path(cwd).resolve()
    for candidate in (current, *current.parents):
        tracks_dir = candidate / ".tracks"
        if (tracks_dir / "install.json").is_file():
            return candidate
        if (tracks_dir / "bin" / "trac.py").is_file() or (
            tracks_dir / "env"
        ).is_dir():
            raise ProjectCorrupt(
                f"{candidate} has install artifacts but no receipt"
            )
    return None


def _relative_inside(root: Path, value: object, field: str) -> Path:
    if not isinstance(value, str) or not value:
        raise ProjectCorrupt(f"receipt {field} is missing")
    relative = Path(value)
    if relative.is_absolute() or ".." in relative.parts:
        raise ProjectCorrupt(f"receipt {field} escapes the project: {value}")
    return Path(root) / relative


def read_receipt(root: Path) -> dict:
    """Load and validate the project receipt (interfaces §1b.1)."""
    receipt_path = Path(root) / RECEIPT_REL
    try:
        data = json.loads(receipt_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ProjectCorrupt(f"cannot read {RECEIPT_REL}: {exc}") from None
    if not isinstance(data, dict):
        raise ProjectCorrupt(f"{RECEIPT_REL} is not a JSON object")
    version = data.get("version")
    if data.get("schema_version") != 1 or not isinstance(version, str) or not version:
        raise ProjectCorrupt("receipt schema_version/version is invalid")
    python = data.get("python")
    if not isinstance(python, str) or not os.path.isabs(python):
        raise ProjectCorrupt("receipt python is not an absolute path")
    site_packages = _relative_inside(root, data.get("site_packages"), "site_packages")
    launcher = _relative_inside(root, data.get("launcher"), "launcher")
    if not site_packages.is_dir():
        raise ProjectCorrupt(f"site-packages is missing: {site_packages}")
    if not launcher.is_file():
        raise ProjectCorrupt(f"launcher is missing: {launcher}")
    init_file = site_packages / "tracks" / "__init__.py"
    try:
        match = _VERSION_ASSIGNMENT.search(init_file.read_text(encoding="utf-8"))
    except OSError:
        raise ProjectCorrupt(f"site-packages package is missing: {init_file}") from None
    if match is None or match.group(1) != version:
        installed = match.group(1) if match is not None else "missing"
        raise ProjectCorrupt(
            f"receipt version {version} != site-packages version {installed}"
        )
    return data


def write_receipt(root: Path, receipt: dict) -> Path:
    """Atomically write the receipt (temp file + rename)."""
    path = Path(root) / RECEIPT_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    with tmp.open("w", encoding="utf-8") as handle:
        json.dump(receipt, handle, indent=2)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(tmp, path)
    return path


def site_packages_path(root: Path, receipt: dict) -> Path:
    return Path(root) / receipt["site_packages"]


def write_launcher(root: Path) -> Path:
    """Write the version-independent project launcher atomically."""
    path = Path(root) / LAUNCHER_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(".trac.py.tmp")
    tmp.write_text(f"#!{sys.executable}\n{LAUNCHER_SOURCE}", encoding="utf-8")
    os.chmod(tmp, 0o755)
    os.replace(tmp, path)
    return path


def _write_if_absent(path: Path, text: str) -> None:
    if not path.exists():
        path.write_text(text, encoding="utf-8")


def scaffold_tracks_dirs(root: Path) -> None:
    """Create the idempotent ``.tracks`` scaffold without touching the host.

    Mirrors the .tracks-level part of ``trac init`` only (FR-0352: the host
    root .gitignore is never created, read or modified by install).
    """
    tracks_dir = Path(root) / ".tracks"
    for name in ("projects", "runtime", "wiki"):
        (tracks_dir / name).mkdir(parents=True, exist_ok=True)
    _write_if_absent(tracks_dir / ".gitignore", TRACKS_GITIGNORE)
    _write_if_absent(tracks_dir / "runtime" / ".gitignore", RUNTIME_GITIGNORE)
    _write_if_absent(tracks_dir / "projects" / ".gitignore", PROJECTS_GITIGNORE)
    for name in ("projects", "wiki"):
        keep = tracks_dir / name / ".gitkeep"
        if not keep.exists():
            keep.write_text("", encoding="utf-8")


# -- background service state (interfaces §1e, IF-SERVERLIFE-001) -------------


def service_home(root: Path) -> Path:
    """The project's runtime service directory (``.tracks/service``)."""
    return Path(root) / SERVICE_DIR_REL


def pidfile_path(home: Path) -> Path:
    return Path(home) / PIDFILE_NAME


def read_pidfile(home: Path) -> dict | None:
    """Load the service pidfile; missing or malformed reads as no service."""
    try:
        data = json.loads(pidfile_path(home).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def write_pidfile(home: Path, payload: dict) -> Path:
    """Atomically write the documented pidfile payload (interfaces §1b.5)."""
    path = pidfile_path(home)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    os.replace(tmp, path)
    return path


def remove_pidfile(home: Path) -> None:
    with contextlib.suppress(OSError):
        pidfile_path(home).unlink()


def pid_alive(pid: object) -> bool:
    """True when *pid* names a live (non-zombie) process."""
    try:
        numeric = int(pid)
    except (TypeError, ValueError):
        return False
    if numeric <= 0:
        return False
    if sys.platform.startswith("win"):
        # ``os.kill(pid, 0)`` terminates a process on Windows; tasklist is the
        # safe read-only probe there (stop/background are POSIX-only anyway).
        return _windows_pid_alive(numeric)
    try:
        os.kill(numeric, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    except OSError:
        return False
    return not _is_zombie(numeric)


def _windows_pid_alive(pid: int) -> bool:
    try:
        completed = subprocess.run(
            ["tasklist", "/FI", f"PID eq {pid}", "/NH"],
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return str(pid) in completed.stdout


def _is_zombie(pid: int) -> bool:
    try:
        completed = subprocess.run(
            ["ps", "-p", str(pid), "-o", "stat="],
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return completed.stdout.strip().upper().startswith("Z")


def process_command(pid: int) -> str | None:
    """The process command line, via /proc when available, else ``ps``."""
    try:
        raw = Path(f"/proc/{pid}/cmdline").read_bytes()
    except OSError:
        raw = b""
    if raw:
        return raw.replace(b"\0", b" ").decode("utf-8", "replace").strip()
    try:
        completed = subprocess.run(
            ["ps", "-p", str(pid), "-o", "command="],
            capture_output=True,
            text=True,
            timeout=2,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return completed.stdout.strip() or None


def launcher_owns_pid(root: Path, receipt: dict, pid: object) -> bool:
    """True when *pid*'s command line runs this project's launcher (§1e.3)."""
    try:
        numeric = int(pid)
    except (TypeError, ValueError):
        return False
    command = process_command(numeric)
    if command is None:
        return False
    launcher = (Path(root) / str(receipt.get("launcher") or "")).resolve()
    return str(launcher) in command


def healthz(host: str, port: object, timeout: float = 0.5) -> tuple[bool, str]:
    """Probe ``/healthz`` on the documented loopback service address."""
    try:
        numeric = int(port)
    except (TypeError, ValueError):
        return False, "invalid port"
    connection = http.client.HTTPConnection(host, numeric, timeout=timeout)
    try:
        connection.request("GET", "/healthz")
        response = connection.getresponse()
        response.read()
        if response.status == 200:
            return True, ""
        return False, f"HTTP {response.status}"
    except (OSError, http.client.HTTPException) as exc:
        return False, str(exc) or exc.__class__.__name__
    finally:
        connection.close()


def pidfile_status(home: Path, receipt: dict, root: Path) -> dict:
    """Classify the pidfile for ``serve --status`` (interfaces §1e.4).

    Stale pidfiles are removed here (the documented cleanup); a live PID is
    probed over ``/healthz`` and reported running or unhealthy.
    """
    payload = read_pidfile(home)
    if payload is None:
        return {"state": "stopped"}
    pid = payload.get("pid")
    if not pid_alive(pid):
        remove_pidfile(home)
        return {"state": "stale"}
    host = str(payload.get("host") or "127.0.0.1")
    try:
        port = int(payload.get("port") or 0)
    except (TypeError, ValueError):
        port = 0
    ok, detail = healthz(host, port)
    result = {
        "state": "running" if ok else "unhealthy",
        "pid": int(pid),
        "version": str(payload.get("version") or receipt.get("version") or ""),
        "url": f"http://{host}:{port}",
    }
    if not ok:
        result["detail"] = detail
    return result


def stop_service(home: Path, receipt: dict, root: Path) -> dict:
    """Stop the recorded service after launcher-ownership validation (§1e.3).

    Returns a state payload; refusal leaves both the process and pidfile
    untouched, while successful/stale paths consume the pidfile.
    """
    payload = read_pidfile(home)
    if payload is None:
        return {"state": "not_running"}
    pid = payload.get("pid")
    if not pid_alive(pid):
        remove_pidfile(home)
        return {"state": "stale_removed"}
    numeric = int(pid)
    if not launcher_owns_pid(root, receipt, numeric):
        return {"state": "refused", "pid": numeric}
    with contextlib.suppress(ProcessLookupError):
        os.kill(numeric, signal.SIGTERM)
    if not _wait_pid_gone(numeric, STOP_TIMEOUT_S):
        with contextlib.suppress(ProcessLookupError):
            os.kill(numeric, signal.SIGKILL)
        _wait_pid_gone(numeric, 1.0)
    remove_pidfile(home)
    return {"state": "stopped", "pid": numeric}


def _wait_pid_gone(pid: int, timeout: float) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if not pid_alive(pid):
            return True
        time.sleep(0.05)
    return not pid_alive(pid)
