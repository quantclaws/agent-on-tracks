"""Project installation runtime: discovery, receipt and launcher (IF-PROJLAYOUT-001).

The receipt at ``<project>/.tracks/install.json`` is the single source of
truth for a project's locked version (interfaces §1b/§1d).  Discovery walks
up from the current directory; install artifacts without a receipt mean the
project is corrupt and must fail closed instead of falling back to the
global version.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

RECEIPT_REL = ".tracks/install.json"
LAUNCHER_REL = ".tracks/bin/trac.py"
SITE_PACKAGES_TEMPLATE = ".tracks/env/{version}/site-packages"

# `.tracks` scaffold gitignores mirror `trac init`'s .tracks-level semantics
# (interfaces §1b.4); the host root .gitignore is deliberately never touched.
RUNTIME_GITIGNORE = "tracks.db*\nblobs/\nlock\nlog/\nprompts/\n"
PROJECTS_GITIGNORE = "*.lock\n*.tmp\n"
TRACKS_GITIGNORE = "report/\n*.lock\n"
ENV_GITIGNORE = "*"

_VERSION_ASSIGNMENT = re.compile(
    r'^__version__\s*=\s*["\']([^"\']+)["\']', re.MULTILINE
)

LAUNCHER_SOURCE = '''"""tracks project launcher (generated by ``trac install``).

Loads the locked site-packages recorded in ``.tracks/install.json`` and
runs the locked CLI from the project root with ``TRAC_PROJECT_ACTIVE=1``.
"""

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main(argv=None):
    receipt = json.loads(
        (ROOT / ".tracks" / "install.json").read_text(encoding="utf-8")
    )
    site_packages = (ROOT / receipt["site_packages"]).resolve()
    sys.path.insert(0, str(site_packages))
    os.chdir(ROOT)
    os.environ["TRAC_PROJECT_ACTIVE"] = "1"
    from tracks.cli.main import main as cli_main

    return cli_main(list(sys.argv[1:] if argv is None else argv))


if __name__ == "__main__":
    raise SystemExit(main())
'''


class ProjectCorrupt(Exception):
    """Install artifacts exist but the receipt/site-packages are unusable."""


def find_project(cwd: Path) -> Path | None:
    """Return the nearest installed project root, or None outside a project.

    Raises :class:`ProjectCorrupt` when a ``.tracks`` directory carries
    install artifacts (launcher or env) without a receipt.
    """
    current = Path(cwd).resolve()
    for candidate in (current, *current.parents):
        tracks_dir = candidate / ".tracks"
        if (tracks_dir / "install.json").is_file():
            return candidate
        if (tracks_dir / "bin" / "trac.py").is_file() or (
            tracks_dir / "env"
        ).is_dir():
            raise ProjectCorrupt(
                f"{candidate} has install artifacts but no receipt"
            )
    return None


def _relative_inside(root: Path, value: object, field: str) -> Path:
    if not isinstance(value, str) or not value:
        raise ProjectCorrupt(f"receipt {field} is missing")
    relative = Path(value)
    if relative.is_absolute() or ".." in relative.parts:
        raise ProjectCorrupt(f"receipt {field} escapes the project: {value}")
    return Path(root) / relative


def read_receipt(root: Path) -> dict:
    """Load and validate the project receipt (interfaces §1b.1)."""
    receipt_path = Path(root) / RECEIPT_REL
    try:
        data = json.loads(receipt_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ProjectCorrupt(f"cannot read {RECEIPT_REL}: {exc}") from None
    if not isinstance(data, dict):
        raise ProjectCorrupt(f"{RECEIPT_REL} is not a JSON object")
    version = data.get("version")
    if data.get("schema_version") != 1 or not isinstance(version, str) or not version:
        raise ProjectCorrupt("receipt schema_version/version is invalid")
    python = data.get("python")
    if not isinstance(python, str) or not os.path.isabs(python):
        raise ProjectCorrupt("receipt python is not an absolute path")
    site_packages = _relative_inside(root, data.get("site_packages"), "site_packages")
    launcher = _relative_inside(root, data.get("launcher"), "launcher")
    if not site_packages.is_dir():
        raise ProjectCorrupt(f"site-packages is missing: {site_packages}")
    if not launcher.is_file():
        raise ProjectCorrupt(f"launcher is missing: {launcher}")
    init_file = site_packages / "tracks" / "__init__.py"
    try:
        match = _VERSION_ASSIGNMENT.search(init_file.read_text(encoding="utf-8"))
    except OSError:
        raise ProjectCorrupt(f"site-packages package is missing: {init_file}") from None
    if match is None or match.group(1) != version:
        installed = match.group(1) if match is not None else "missing"
        raise ProjectCorrupt(
            f"receipt version {version} != site-packages version {installed}"
        )
    return data


def write_receipt(root: Path, receipt: dict) -> Path:
    """Atomically write the receipt (temp file + rename)."""
    path = Path(root) / RECEIPT_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    with tmp.open("w", encoding="utf-8") as handle:
        json.dump(receipt, handle, indent=2)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(tmp, path)
    return path


def site_packages_path(root: Path, receipt: dict) -> Path:
    return Path(root) / receipt["site_packages"]


def write_launcher(root: Path) -> Path:
    """Write the version-independent project launcher atomically."""
    path = Path(root) / LAUNCHER_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(".trac.py.tmp")
    tmp.write_text(f"#!{sys.executable}\n{LAUNCHER_SOURCE}", encoding="utf-8")
    os.chmod(tmp, 0o755)
    os.replace(tmp, path)
    return path


def _write_if_absent(path: Path, text: str) -> None:
    if not path.exists():
        path.write_text(text, encoding="utf-8")


def scaffold_tracks_dirs(root: Path) -> None:
    """Create the idempotent ``.tracks`` scaffold without touching the host.

    Mirrors the .tracks-level part of ``trac init`` only (FR-0352: the host
    root .gitignore is never created, read or modified by install).
    """
    tracks_dir = Path(root) / ".tracks"
    for name in ("projects", "runtime", "wiki"):
        (tracks_dir / name).mkdir(parents=True, exist_ok=True)
    _write_if_absent(tracks_dir / ".gitignore", TRACKS_GITIGNORE)
    _write_if_absent(tracks_dir / "runtime" / ".gitignore", RUNTIME_GITIGNORE)
    _write_if_absent(tracks_dir / "projects" / ".gitignore", PROJECTS_GITIGNORE)
    for name in ("projects", "wiki"):
        keep = tracks_dir / name / ".gitkeep"
        if not keep.exists():
            keep.write_text("", encoding="utf-8")
